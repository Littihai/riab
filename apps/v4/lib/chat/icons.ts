// Flat lookup: "faces/smile" -> icon. Namespaced by category so the same word
// (e.g. "heart") can exist in two categories without clashing.
export const CHAT_ICONS: Record<string, ChatIcon> = Object.fromEntries(
  ICON_CATEGORIES.flatMap((category) =>
    Object.entries(category.icons).map(([name, Icon]) => [
      `${category.id}/${name}`,
      { name: `${category.id}/${name}`, Icon, category: category.id },
    ])
  )
)

export const CHAT_ICON_COUNT = Object.keys(CHAT_ICONS).length

export function getIconTone(id: string) {
  const category = ICON_CATEGORIES.find((c) => id.startsWith(`${c.id}/`))
  return category?.tone ?? "bg-muted text-foreground"
}
